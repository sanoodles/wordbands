// Writes src/app/fondue.css: Fondue's stylesheet cut down to the components the app imports.
// Fondue ships one 361KB stylesheet for every component, and it blocks the first paint.
// `fondue-css.test.ts` fails when a Fondue upgrade or a new import leaves the file stale.
//
//   pnpm --filter @wordbands/web build:fondue-css

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { pathToFileURL } from "node:url";
import postcss from "postcss";

const APP = join(import.meta.dirname, "..");
export const OUTPUT = join(APP, "src/app/fondue.css");
const HEADER = "/* Generated by scripts/build-fondue-css.ts. Do not edit. */\n";

const STYLESHEET = createRequire(join(APP, "package.json")).resolve("@frontify/fondue/components/styles");
// pnpm keeps it beside @frontify/fondue. Its exports name no CommonJS entry to resolve.
const COMPONENTS = join(dirname(STYLESHEET), "../../../../fondue-components/dist");

// A CSS module's class, as Vite hashes it: _root_1c6io_2.
const MODULE_CLASS = /_[A-Za-z][\w-]*_[a-z0-9]{5}_\d+/g;
const IMPORT = /import\s*\{([^}]*)\}\s*from\s*"@frontify\/fondue\/components"/g;

function sourceFiles(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return sourceFiles(path);
    return /\.tsx?$/.test(entry.name) && !entry.name.includes(".test.") ? [path] : [];
  });
}

function importedComponents(): string[] {
  const names = sourceFiles(join(APP, "src")).flatMap((file) =>
    [...readFileSync(file, "utf8").matchAll(IMPORT)].flatMap(([, list]) =>
      list!.split(",").map((name) => name.trim().split(/\s+as\s+/)[0]!),
    ),
  );
  return [...new Set(names)].filter(Boolean).sort();
}

const siblings = (source: string) => [...source.matchAll(/(?:from|import\(?)\s*"\.\/([^"]+)"/g)].map((m) => m[1]!);
const read = (file: string) => readFileSync(join(COMPONENTS, file), "utf8");

/** Walks Fondue's own imports from each component, so a part it renders inside is kept too. */
function classesOf(components: string[]): Set<string> {
  const barrel = read("fondue-components.js");
  const files = components.map((name) => {
    const local = new RegExp(`(\\w+) as ${name}\\b`).exec(barrel.slice(barrel.lastIndexOf("export")))?.[1];
    const from = local && new RegExp(`\\b${name} as ${local}\\b[^}]*\\}\\s*from\\s*"\\./([^"]+)"`).exec(barrel)?.[1];
    if (!from) throw new Error(`${name} is not a component of @frontify/fondue-components`);
    return from;
  });
  const seen = new Set<string>();
  const classes = new Set<string>();
  while (files.length > 0) {
    const file = files.pop()!;
    if (seen.has(file)) continue;
    seen.add(file);
    const source = read(file);
    for (const [name] of source.matchAll(MODULE_CLASS)) classes.add(name);
    files.push(...siblings(source));
  }
  return classes;
}

export function buildFondueCss(): string {
  const used = classesOf(importedComponents());
  const root = postcss.parse(readFileSync(STYLESHEET, "utf8"));
  root.walkAtRules("charset", (rule) => {
    rule.remove();
  });

  root.walkRules((rule) => {
    if (rule.parent?.type === "atrule" && /keyframes$/.test((rule.parent as postcss.AtRule).name)) return;
    // A class inside :not() rules nothing out, so it says nothing about the selector.
    const kept = rule.selectors.filter((selector) =>
      [...selector.replace(/:not\([^)]*\)/g, "").matchAll(MODULE_CLASS)].every(([name]) => used.has(name)),
    );
    if (kept.length === 0) rule.remove();
    else rule.selectors = kept;
  });

  const declared: string[] = [];
  root.walkDecls(/animation/, (decl) => {
    declared.push(decl.value);
  });
  const animations = declared.join(" ");
  root.walkAtRules(/keyframes$/, (rule) => {
    if (!animations.includes(rule.params)) rule.remove();
  });
  root.walkAtRules((rule) => {
    if (rule.nodes?.length === 0) rule.remove();
  });
  // Every Fondue component registers the custom properties it animates, once per component.
  const named = root.clone();
  named.walkAtRules("property", (rule) => {
    rule.remove();
  });
  const rest = named.toString();
  const registered = new Set<string>();
  root.walkAtRules("property", (rule) => {
    if (registered.has(rule.params) || !rest.includes(rule.params)) rule.remove();
    else registered.add(rule.params);
  });
  return HEADER + root.toString() + "\n";
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const css = buildFondueCss();
  writeFileSync(OUTPUT, css);
  console.log(`${OUTPUT}: ${(css.length / 1024).toFixed(0)}KB`);
}
